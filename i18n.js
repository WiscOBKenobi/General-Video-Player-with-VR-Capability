  let language = 'en';
  function t(key, values = {}) {
    const message = messages[language][key] ?? messages.en[key];
    if (message === undefined) throw new Error(`Unknown translation: ${key}`);
    return message.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
  }
  function setLanguage(value) {
    if (!Object.hasOwn(messages, value)) return;
    language = value;
    document.documentElement.lang = language;
    for (const attribute of ['text', 'title', 'aria-label', 'content']) {
      const marker = attribute === 'text' ? 'data-i18n' : `data-i18n-${attribute}`;
      document.querySelectorAll(`[${marker}]`).forEach(element => {
        const text = t(element.getAttribute(marker));
        if (attribute === 'text') element.textContent = text;
        else element.setAttribute(attribute, text);
      });
    }
    document.querySelectorAll('[data-language]').forEach(button => button.setAttribute('aria-pressed', button.dataset.language === language));
  }
  return { t, setLanguage };
